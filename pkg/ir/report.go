// StatusReportIR is the canonical, strictly validated operational analysis report generated by the LLM.
type StatusReportIR struct {
	SchemaVersion                string               `json:"schemaVersion"`
	OverallStatus                string               `json:"overallStatus"`
	Confidence                   string               `json:"confidence"`
	ExecutiveSummary             string               `json:"executiveSummary"`
	Timeline                     []ReportTimelineItem `json:"timeline"`
	Findings                     []ReportFinding      `json:"findings"`
	Hypotheses                   []ReportHypothesis   `json:"hypotheses"`
	RecommendedActions           []ReportAction       `json:"recommendedActions"`
	DataGaps                     []string             `json:"dataGaps"`
	SuggestedInvestigationIntent string               `json:"suggestedInvestigationIntent,omitempty"`
}

// ReportTimelineItem represents a single ordered event grounded in supplied evidence.
type ReportTimelineItem struct {
	Timestamp   string   `json:"timestamp"`
	Event       string   `json:"event"`
	EvidenceIDs []string `json:"evidenceIds"`
}

// ReportFinding represents a single grounded operational finding.
type ReportFinding struct {
	ID          string   `json:"id"`
	Category    string   `json:"category"`
	Severity    string   `json:"severity"`
	Title       string   `json:"title"`
	Detail      string   `json:"detail"`
	EvidenceIDs []string `json:"evidenceIds"`
}

// ReportHypothesis represents a grounded root-cause hypothesis with verification steps.
type ReportHypothesis struct {
	Title             string   `json:"title"`
	Likelihood        string   `json:"likelihood"`
	Rationale         string   `json:"rationale"`
	EvidenceIDs       []string `json:"evidenceIds"`
	VerificationSteps []string `json:"verificationSteps"`
}

// ReportAction represents a prioritized operational next step linked to findings.
type ReportAction struct {
	Priority          string   `json:"priority"`
	Action            string   `json:"action"`
	RelatedFindingIds []string `json:"relatedFindingIds"`
}

// ReportDashboardContext captures non-sensitive metadata about the analyzed dashboard.
type ReportDashboardContext struct {
	UID                string `json:"uid,omitempty"`
	Title              string `json:"title"`
	PanelCount         int    `json:"panelCount"`
	AnalyzedPanelCount int    `json:"analyzedPanelCount"`
}

// ReportCollectionStatus records which evidence sources were successfully queried.
type ReportCollectionStatus struct {
	AlertsChecked       bool `json:"alertsChecked"`
	RulesChecked        bool `json:"rulesChecked"`
	TotalRulesEvaluated int  `json:"totalRulesEvaluated"`
	ActiveAlertsTotal   int  `json:"activeAlertsTotal"`
	AbnormalRulesTotal  int  `json:"abnormalRulesTotal"`
}

// AlertEvidenceItem summarizes a single Grafana Alertmanager alert instance.
type AlertEvidenceItem struct {
	ID           string            `json:"id"`
	AlertName    string            `json:"alertName"`
	State        string            `json:"state"`
	Severity     string            `json:"severity,omitempty"`
	StartsAt     string            `json:"startsAt,omitempty"`
	Labels       map[string]string `json:"labels,omitempty"`
	Summary      string            `json:"summary,omitempty"`
	Description  string            `json:"description,omitempty"`
	MatchesScope bool              `json:"matchesScope,omitempty"`
}

// RuleEvidenceItem summarizes an abnormal Grafana Alerting rule evaluation state.
type RuleEvidenceItem struct {
	ID                string `json:"id"`
	RuleName          string `json:"ruleName"`
	Group             string `json:"group,omitempty"`
	State             string `json:"state"`
	Health            string `json:"health"`
	LastError         string `json:"lastError,omitempty"`
	ActiveAlertsCount int    `json:"activeAlertsCount"`
	MatchesScope      bool   `json:"matchesScope,omitempty"`
}

// MetricWindowStats holds deterministic summary statistics for a single metric series window.
type MetricWindowStats struct {
	Latest       *float64 `json:"latest,omitempty"`
	Avg          float64  `json:"avg"`
	P95          float64  `json:"p95"`
	Min          float64  `json:"min"`
	Max          float64  `json:"max"`
	SampleCount  int      `json:"sampleCount"`
	MissingRatio float64  `json:"missingRatio"`
	PeakAt       string   `json:"peakAt,omitempty"`
}

// MetricBaselineStats holds summary statistics for the baseline comparison window.
type MetricBaselineStats struct {
	Avg float64 `json:"avg"`
	P95 float64 `json:"p95"`
	Max float64 `json:"max"`
}

// MetricEvidenceItem summarizes a single queried dashboard series and its baseline comparison.
type MetricEvidenceItem struct {
	ID                string               `json:"id"`
	PanelTitle        string               `json:"panelTitle"`
	Unit              string               `json:"unit,omitempty"`
	SeriesLabel       string               `json:"seriesLabel,omitempty"`
	QueryStatus       string               `json:"queryStatus"`
	ErrorText         string               `json:"errorText,omitempty"`
	Current           *MetricWindowStats   `json:"current,omitempty"`
	Baseline          *MetricBaselineStats `json:"baseline,omitempty"`
	DeltaPctAvg       *float64             `json:"deltaPctAvg,omitempty"`
	DeltaPctP95       *float64             `json:"deltaPctP95,omitempty"`
	BaselineWasZero   bool                 `json:"baselineWasZero,omitempty"`
	Trend             string               `json:"trend"`
	ThresholdBreached string               `json:"thresholdBreached"`
	AnomalyHint       string               `json:"anomalyHint"`
}

// StatusNoteEvidenceItem carries a deterministic collection status note (e.g., healthy 0-alert check).
type StatusNoteEvidenceItem struct {
	ID      string `json:"id"`
	Message string `json:"message"`
}

// CollectionWarningItem captures partial collection failures or truncation with a citable ev-warn-* ID.
type CollectionWarningItem struct {
	ID      string `json:"id"`
	Code    string `json:"code"`
	Message string `json:"message"`
}

// ReportEvidenceBundle carries all bounded, browser-collected evidence for a single analysis request.
type ReportEvidenceBundle struct {
	CollectedAt string                   `json:"collectedAt"`
	Alerts      []AlertEvidenceItem      `json:"alerts"`
	Rules       []RuleEvidenceItem       `json:"rules"`
	Metrics     []MetricEvidenceItem     `json:"metrics"`
	StatusNotes []StatusNoteEvidenceItem `json:"statusNotes,omitempty"`
}

// AnalyzeStatusPayload is the strictly typed request body for POST /jobs/analyze.
type AnalyzeStatusPayload struct {
	DatasourceUID      string                  `json:"datasourceUid,omitempty"`
	Scope              *ScopeFilter            `json:"scope,omitempty"`
	Window             string                  `json:"window"`
	BaselineMode       string                  `json:"baselineMode"`
	Language           string                  `json:"language"`
	UserFocus          string                  `json:"userFocus,omitempty"`
	DashboardContext   *ReportDashboardContext `json:"dashboardContext,omitempty"`
	CollectionStatus   ReportCollectionStatus  `json:"collectionStatus"`
	Evidence           ReportEvidenceBundle    `json:"evidence"`
	CollectionWarnings []CollectionWarningItem `json:"collectionWarnings,omitempty"`
}

// Clone returns a deep copy of StatusReportIR so callers and stores never share mutable slices.
func (r StatusReportIR) Clone() StatusReportIR {
	out := r
	if r.Timeline != nil {
		out.Timeline = make([]ReportTimelineItem, len(r.Timeline))
		for i, item := range r.Timeline {
			itemCopy := item
			if item.EvidenceIDs != nil {
				itemCopy.EvidenceIDs = append([]string(nil), item.EvidenceIDs...)
			}
			out.Timeline[i] = itemCopy
		}
	}
	if r.Findings != nil {
		out.Findings = make([]ReportFinding, len(r.Findings))
		for i, f := range r.Findings {
			fCopy := f
			if f.EvidenceIDs != nil {
				fCopy.EvidenceIDs = append([]string(nil), f.EvidenceIDs...)
			}
			out.Findings[i] = fCopy
		}
	}
	if r.Hypotheses != nil {
		out.Hypotheses = make([]ReportHypothesis, len(r.Hypotheses))
		for i, h := range r.Hypotheses {
			hCopy := h
			if h.EvidenceIDs != nil {
				hCopy.EvidenceIDs = append([]string(nil), h.EvidenceIDs...)
			}
			if h.VerificationSteps != nil {
				hCopy.VerificationSteps = append([]string(nil), h.VerificationSteps...)
			}
			out.Hypotheses[i] = hCopy
		}
	}
	if r.RecommendedActions != nil {
		out.RecommendedActions = make([]ReportAction, len(r.RecommendedActions))
		for i, a := range r.RecommendedActions {
			aCopy := a
			if a.RelatedFindingIds != nil {
				aCopy.RelatedFindingIds = append([]string(nil), a.RelatedFindingIds...)
			}
			out.RecommendedActions[i] = aCopy
		}
	}
	if r.DataGaps != nil {
		out.DataGaps = append([]string(nil), r.DataGaps...)
	}
	return out
}
