var validMockLabelName = regexp.MustCompile(`^[a-zA-Z_][a-zA-Z0-9_]*$`)

// MockClient is an EXPLICIT development/test-only deterministic LLM adapter.
// Production configuration MUST NOT silently fall back to MockClient on real LLM errors.
type MockClient struct {
	// InjectSyntaxErrorOnFirstGenerate can be enabled in tests to exercise repair flows.
	InjectSyntaxErrorOnFirstGenerate bool
	// Delay optionally simulates LLM inference latency in dev/test environments while honoring
	// ctx.Done() immediately so SSE chunk flushing and client-disconnect cancellation can be verified live.
	Delay         time.Duration
	generateCount atomic.Int64
}

func (m *MockClient) waitDelay(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if m.Delay <= 0 {
		return nil
	}
	timer := time.NewTimer(m.Delay)
	defer timer.Stop()
	select {
	case <-timer.C:
		return nil
	case <-ctx.Done():
		return ctx.Err()
	}
}

func (m *MockClient) Enabled(_ context.Context) (bool, error) {
	return true, nil
}

func (m *MockClient) GenerateIR(ctx context.Context, req GenerateRequest) ([]byte, CompletionMeta, error) {
	if err := m.waitDelay(ctx); err != nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, err
	}
	count := m.generateCount.Add(1)

	selector := buildScopeMatcher(req.Scope)
	hasReq, reqMetric := findMetric(req.Catalog, "http_requests_total", "requests_total", "http_server_requests_total")
	hasDur, durMetric := findMetric(req.Catalog, "http_request_duration_seconds_bucket", "request_duration_seconds_bucket")
	hasCPU, cpuMetric := findMetric(req.Catalog, "process_cpu_seconds_total", "container_cpu_usage_seconds_total")
	hasMem, memMetric := findMetric(req.Catalog, "process_resident_memory_bytes", "container_memory_working_set_bytes")

	lowerIntent := strings.ToLower(req.UserIntent)
	wantError := containsAny(lowerIntent, "error", "エラー", "5xx", "red")
	wantLatency := containsAny(lowerIntent, "latency", "レイテンシ", "p95", "duration", "red")
	wantReq := containsAny(lowerIntent, "request", "リクエスト", "rps", "traffic", "red")
	wantCPU := containsAny(lowerIntent, "cpu")
	wantMem := containsAny(lowerIntent, "mem", "メモリ")
	wantVariable := containsAny(lowerIntent, "variable", "変数", "$service")
	wantMultiQuery := containsAny(lowerIntent, "multi", "p50", "p99", "マルチクエリ", "比較")

	var variables []ir.VariableIR
	if wantVariable {
		metricHint := ""
		secondaryLabel := ""
		if hasReq {
			metricHint = reqMetric.Name
			for _, lbl := range reqMetric.Labels {
				if (req.Scope == nil || lbl != req.Scope.LabelName) && validMockLabelName.MatchString(lbl) && !ir.IsReservedVariableName(lbl) && len(lbl) <= ir.MaxVariableNameLen {
					secondaryLabel = lbl
					break
				}
			}
		} else if len(req.Catalog) > 0 {
			metricHint = req.Catalog[0].Name
			for _, lbl := range req.Catalog[0].Labels {
				if (req.Scope == nil || lbl != req.Scope.LabelName) && validMockLabelName.MatchString(lbl) && !ir.IsReservedVariableName(lbl) && len(lbl) <= ir.MaxVariableNameLen {
					secondaryLabel = lbl
					break
				}
			}
		}
		if metricHint != "" && secondaryLabel != "" {
			defaultVal := "200"
			if secondaryLabel != "status" {
				defaultVal = "default"
			}
			variables = append(variables, ir.VariableIR{
				Name:          secondaryLabel,
				Label:         strings.ToUpper(secondaryLabel[:1]) + secondaryLabel[1:],
				Type:          "query",
				DatasourceRef: ir.SelectedDatasourceRef,
				LabelName:     secondaryLabel,
				MetricName:    metricHint,
				DefaultValue:  defaultVal,
			})
		} else {
			variables = append(variables, ir.VariableIR{
				Name:         "status_class",
				Label:        "Error Status Regex",
				Type:         "custom",
				Options:      []string{"5..", "4..|5.."},
				DefaultValue: "5..",
			})
		}
	}

	isMetricsQL := strings.EqualFold(strings.TrimSpace(req.QueryKind), "metricsql")
	queryKind := ""
	if isMetricsQL {
		queryKind = "metricsql"
	}

	if len(req.Catalog) == 0 {
		return nil, CompletionMeta{ProviderMode: "mock"}, ErrInsufficientMetrics
	}
	if !hasReq && !hasDur && !hasCPU && !hasMem {
		matched, ok := findAnyOverlappingMetric(req.Catalog, lowerIntent)
		if !ok {
			return nil, CompletionMeta{ProviderMode: "mock"}, ErrInsufficientMetrics
		}
		expr := fmt.Sprintf("%s%s", matched.Name, selector)
		if strings.EqualFold(matched.Type, "counter") || strings.HasSuffix(matched.Name, "_total") {
			if isMetricsQL {
				expr = fmt.Sprintf("rate(%s%s[5m]) default 0", matched.Name, selector)
			} else {
				expr = fmt.Sprintf("rate(%s%s[5m])", matched.Name, selector)
			}
		}
		doc := ir.DashboardIR{
			SchemaVersion: ir.SchemaVersion,
			Revision:      1,
			Title:         titleFromScope(req.Scope, "Generated Metrics Dashboard"),
			Description:   "Generated by dev mock LLM strictly from scoped catalog metrics.",
			TimeRange:     ir.TimeRange{From: "now-15m", To: "now"},
			Variables:     variables,
			Panels: []ir.PanelIR{
				{
					ID:            "panel-primary-metric",
					Type:          "timeseries",
					Title:         matched.Name,
					DatasourceRef: ir.SelectedDatasourceRef,
					Query:         ir.QueryIR{Kind: queryKind, Expr: expr, LegendFormat: "{{instance}}"},
					Unit:          inferUnit(matched),
					Layout:        ir.LayoutHint{Row: 0, Col: 0, Width: "full"},
				},
			},
		}
		raw, err := json.Marshal(doc)
		return raw, CompletionMeta{FinishReason: "stop", Model: "mock-deterministic-v1", ProviderMode: "mock"}, err
	}

	var panels []ir.PanelIR
	maxPanels := req.MaxPanels
	if maxPanels <= 0 || maxPanels > ir.MaxPanelsHardCap {
		maxPanels = ir.DefaultMaxPanels
	}

	if hasReq && (wantReq || (!wantError && !wantLatency && !wantCPU && !wantMem)) {
		expr := fmt.Sprintf("sum by (status) (rate(%s%s[5m]))", reqMetric.Name, selector)
		if isMetricsQL {
			expr = fmt.Sprintf("sum by (status) (rate(%s%s[5m])) default 0", reqMetric.Name, selector)
		}
		if m.InjectSyntaxErrorOnFirstGenerate && count == 1 {
			expr = fmt.Sprintf("sum by (status) (rate(%s%s[5m]))))", reqMetric.Name, selector)
		}
		panelType := "timeseries"
		if containsAny(lowerIntent, "table", "テーブル") {
			panelType = "table"
		} else if containsAny(lowerIntent, "piechart", "pie", "円グラフ") {
			panelType = "piechart"
		} else if containsAny(lowerIntent, "bargauge", "バーゲージ") {
			panelType = "bargauge"
		}
		panels = append(panels, ir.PanelIR{
			ID:            "panel-request-rate",
			Type:          panelType,
			Title:         "Request Rate",
			Description:   "Requests per second grouped by HTTP status.",
			DatasourceRef: ir.SelectedDatasourceRef,
			Query:         ir.QueryIR{Kind: queryKind, Expr: expr, LegendFormat: "{{status}}"},
			Unit:          "reqps",
			Layout:        ir.LayoutHint{Row: 0, Col: 0, Width: "half"},
		})
	}
	if hasReq && wantError && len(panels) < maxPanels {
		errSelector := buildScopeMatcherWithExtra(req.Scope, `status=~"5.."`)
		expr := fmt.Sprintf(
			"sum(rate(%s%s[5m])) / clamp_min(sum(rate(%s%s[5m])), 1e-9)",
			reqMetric.Name, errSelector, reqMetric.Name, selector,
		)
		if isMetricsQL {
			expr = fmt.Sprintf(
				"sum(increase_pure(%s%s[5m])) / clamp_min(sum(increase_pure(%s%s[5m])), 1e-9) default 0",
				reqMetric.Name, errSelector, reqMetric.Name, selector,
			)
		}
		errPanelType := "stat"
		if containsAny(lowerIntent, "gauge", "ゲージ") && !containsAny(lowerIntent, "bargauge") {
			errPanelType = "gauge"
		}
		panels = append(panels, ir.PanelIR{
			ID:            "panel-error-rate",
			Type:          errPanelType,
			Title:         "5xx Error Ratio",
			Description:   "Share of HTTP 5xx responses over total requests.",
			DatasourceRef: ir.SelectedDatasourceRef,
			Query:         ir.QueryIR{Kind: queryKind, Expr: expr, LegendFormat: "5xx ratio"},
			Unit:          "percentunit",
			Thresholds: []ir.ThresholdIR{
				{Value: 0, Color: "green"},
				{Value: 0.01, Color: "yellow"},
				{Value: 0.05, Color: "red"},
			},
			Layout: ir.LayoutHint{Row: 0, Col: 1, Width: "half"},
		})
	}
	if hasDur && wantLatency && len(panels) < maxPanels {
		latPanel := ir.PanelIR{
			ID:            "panel-latency-p95",
			Type:          "timeseries",
			Title:         "p95 Request Latency",
			Description:   "95th percentile request duration.",
			DatasourceRef: ir.SelectedDatasourceRef,
			Unit:          "s",
			Thresholds: []ir.ThresholdIR{
				{Value: 0, Color: "green"},
				{Value: 0.5, Color: "yellow"},
				{Value: 1.0, Color: "red"},
			},
			Layout: ir.LayoutHint{Row: 1, Col: 0, Width: "full"},
		}
		if wantMultiQuery {
			latPanel.Title = "Request Latency (p50 / p95 / p99)"
			latPanel.Queries = []ir.QueryIR{
				{RefID: "A", Kind: queryKind, Expr: fmt.Sprintf("histogram_quantile(0.50, sum by (le) (rate(%s%s[5m])))", durMetric.Name, selector), LegendFormat: "p50"},
				{RefID: "B", Kind: queryKind, Expr: fmt.Sprintf("histogram_quantile(0.95, sum by (le) (rate(%s%s[5m])))", durMetric.Name, selector), LegendFormat: "p95"},
				{RefID: "C", Kind: queryKind, Expr: fmt.Sprintf("histogram_quantile(0.99, sum by (le) (rate(%s%s[5m])))", durMetric.Name, selector), LegendFormat: "p99"},
			}
		} else {
			latPanel.Query = ir.QueryIR{
				Kind:         queryKind,
				Expr:         fmt.Sprintf("histogram_quantile(0.95, sum by (le) (rate(%s%s[5m])))", durMetric.Name, selector),
				LegendFormat: "p95",
			}
		}
		panels = append(panels, latPanel)
	}
	if hasCPU && wantCPU && len(panels) < maxPanels {
		panels = append(panels, ir.PanelIR{
			ID:            "panel-cpu-usage",
			Type:          "timeseries",
			Title:         "CPU Usage Rate",
			DatasourceRef: ir.SelectedDatasourceRef,
			Query:         ir.QueryIR{Kind: queryKind, Expr: fmt.Sprintf("sum(rate(%s%s[5m]))", cpuMetric.Name, selector), LegendFormat: "cpu"},
			Unit:          "short",
			Layout:        ir.LayoutHint{Row: 2, Col: 0, Width: "half"},
		})
	}
	if hasMem && wantMem && len(panels) < maxPanels {
		memType := "stat"
		if containsAny(lowerIntent, "state-timeline", "timeline", "タイムライン") {
			memType = "state-timeline"
		}
		panels = append(panels, ir.PanelIR{
			ID:            "panel-memory-bytes",
			Type:          memType,
			Title:         "Resident Memory",
			DatasourceRef: ir.SelectedDatasourceRef,
			Query:         ir.QueryIR{Kind: queryKind, Expr: fmt.Sprintf("avg(%s%s)", memMetric.Name, selector), LegendFormat: "memory"},
			Unit:          "bytes",
			Layout:        ir.LayoutHint{Row: 2, Col: 1, Width: "half"},
		})
	}

	if len(panels) == 0 {
		return nil, CompletionMeta{ProviderMode: "mock"}, ErrInsufficientMetrics
	}

	assignCompactGrid(panels)

	desc := "Generated by dev mock LLM from scoped Prometheus metadata."
	if isMetricsQL {
		desc = "Generated by dev mock LLM from scoped VictoriaMetrics metadata (MetricsQL)."
	}
	doc := ir.DashboardIR{
		SchemaVersion: ir.SchemaVersion,
		Revision:      1,
		Title:         titleFromScope(req.Scope, "Service Observability Overview"),
		Description:   desc,
		TimeRange:     ir.TimeRange{From: "now-15m", To: "now"},
		Variables:     variables,
		Panels:        panels,
	}
	raw, err := json.Marshal(doc)
	return raw, CompletionMeta{FinishReason: "stop", Model: "mock-deterministic-v1", ProviderMode: "mock"}, err
}

func (m *MockClient) GeneratePatch(ctx context.Context, req PatchRequest) ([]byte, CompletionMeta, error) {
	if err := m.waitDelay(ctx); err != nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, err
	}
	lower := strings.ToLower(req.EditIntent)
	targetID := req.TargetPanelID
	if targetID == "" {
		for _, p := range req.CurrentIR.Panels {
			if (containsAny(lower, "error", "エラー") && strings.Contains(p.ID, "error")) ||
				(containsAny(lower, "latency", "レイテンシ", "p99", "p95") && strings.Contains(p.ID, "latency")) ||
				(containsAny(lower, "request", "リクエスト") && strings.Contains(p.ID, "request")) {
				targetID = p.ID
				break
			}
		}
	}
	if targetID == "" && len(req.CurrentIR.Panels) > 0 {
		targetID = req.CurrentIR.Panels[0].ID
	}

	var target *ir.PanelIR
	for i := range req.CurrentIR.Panels {
		if req.CurrentIR.Panels[i].ID == targetID {
			target = &req.CurrentIR.Panels[i]
			break
		}
	}
	if target == nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, fmt.Errorf("%w: %q", ir.ErrPanelNotFound, targetID)
	}

	upd := &ir.PanelUpdate{}
	summary := fmt.Sprintf("Updated panel %s", target.ID)

	switch {
	case containsAny(lower, "state-timeline", "タイムライン"):
		upd.Type = "state-timeline"
		summary = fmt.Sprintf("Changed %s visualization to state-timeline", target.ID)
	case containsAny(lower, "bargauge", "バーゲージ"):
		upd.Type = "bargauge"
		summary = fmt.Sprintf("Changed %s visualization to bargauge", target.ID)
	case containsAny(lower, "gauge", "ゲージ"):
		upd.Type = "gauge"
		summary = fmt.Sprintf("Changed %s visualization to gauge", target.ID)
	case containsAny(lower, "piechart", "pie", "円グラフ"):
		upd.Type = "piechart"
		summary = fmt.Sprintf("Changed %s visualization to piechart", target.ID)
	case containsAny(lower, "table", "テーブル"):
		upd.Type = "table"
		summary = fmt.Sprintf("Changed %s visualization to table", target.ID)
	case containsAny(lower, "timeseries", "時系列", "折れ線", "グラフ"):
		upd.Type = "timeseries"
		summary = fmt.Sprintf("Changed %s visualization to timeseries", target.ID)
	case containsAny(lower, "stat", "数値", "カード"):
		upd.Type = "stat"
		summary = fmt.Sprintf("Changed %s visualization to stat", target.ID)
	}

	primaryExpr := ""
	if qs := target.EffectiveQueries(); len(qs) > 0 {
		primaryExpr = qs[0].Expr
	}

	if containsAny(lower, "p99") && strings.Contains(primaryExpr, "0.95") {
		legend := "p99"
		upd.Query = &ir.QueryUpdate{
			Expr:         strings.Replace(primaryExpr, "0.95", "0.99", 1),
			LegendFormat: &legend,
		}
		upd.Title = "p99 Request Latency"
		summary = fmt.Sprintf("Updated %s quantile from p95 to p99", target.ID)
	} else if containsAny(lower, "4xx") && strings.Contains(primaryExpr, `5..`) {
		legend := "4xx/5xx ratio"
		upd.Query = &ir.QueryUpdate{
			Expr:         strings.Replace(primaryExpr, `status=~"5.."`, `status=~"4..|5.."`, 1),
			LegendFormat: &legend,
		}
		upd.Title = "4xx & 5xx Error Ratio"
		summary = fmt.Sprintf("Expanded %s error matcher to 4xx and 5xx", target.ID)
	} else if containsAny(lower, "閾値", "threshold") {
		th := []ir.ThresholdIR{
			{Value: 0, Color: "green"},
			{Value: 0.02, Color: "orange"},
			{Value: 0.1, Color: "red"},
		}
		upd.Thresholds = &th
		summary = fmt.Sprintf("Adjusted thresholds on %s", target.ID)
	} else if upd.Type == "" {
		upd.Title = target.Title + " (Updated)"
	}

	patch := ir.DashboardPatch{
		SchemaVersion: ir.SchemaVersion,
		BaseRevision:  req.CurrentIR.Revision,
		Summary:       summary,
		Operations: []ir.PatchOperation{
			{
				Op:      "update_panel",
				PanelID: target.ID,
				Panel:   upd,
			},
		},
	}
	raw, err := json.Marshal(patch)
	return raw, CompletionMeta{FinishReason: "stop", Model: "mock-deterministic-v1", ProviderMode: "mock"}, err
}

func (m *MockClient) RepairPanels(ctx context.Context, req RepairRequest) ([]byte, CompletionMeta, error) {
	if err := m.waitDelay(ctx); err != nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, err
	}
	selector := buildScopeMatcher(req.Scope)
	hasReq, reqMetric := findMetric(req.Catalog, "http_requests_total", "requests_total")

	isMetricsQL := strings.EqualFold(strings.TrimSpace(req.QueryKind), "metricsql")
	var kindPtr *string
	if isMetricsQL {
		k := "metricsql"
		kindPtr = &k
	}

	var ops []ir.PatchOperation
	for _, t := range req.Targets {
		if len(t.Queries) > 0 {
			repairedQueries := make([]ir.QueryIR, len(t.Queries))
			for i, q := range t.Queries {
				repaired := strings.TrimSuffix(strings.TrimSpace(q.Expr), "))")
				if i == 0 && hasReq {
					if isMetricsQL {
						repaired = fmt.Sprintf("sum by (status) (rate(%s%s[5m])) default 0", reqMetric.Name, selector)
					} else {
						repaired = fmt.Sprintf("sum by (status) (rate(%s%s[5m]))", reqMetric.Name, selector)
					}
				}
				qKind := q.Kind
				if qKind == "" && isMetricsQL {
					qKind = "metricsql"
				}
				repairedQueries[i] = ir.QueryIR{
					RefID:        q.RefID,
					Kind:         qKind,
					Expr:         repaired,
					LegendFormat: q.LegendFormat,
				}
			}
			ops = append(ops, ir.PatchOperation{
				Op:      "update_panel",
				PanelID: t.PanelID,
				Panel: &ir.PanelUpdate{
					Queries: &repairedQueries,
				},
			})
			continue
		}
		repaired := strings.TrimSuffix(strings.TrimSpace(t.Expr), "))")
		if hasReq {
			if isMetricsQL {
				repaired = fmt.Sprintf("sum by (status) (rate(%s%s[5m])) default 0", reqMetric.Name, selector)
			} else {
				repaired = fmt.Sprintf("sum by (status) (rate(%s%s[5m]))", reqMetric.Name, selector)
			}
		}
		ops = append(ops, ir.PatchOperation{
			Op:      "update_panel",
			PanelID: t.PanelID,
			Panel: &ir.PanelUpdate{
				Query: &ir.QueryUpdate{Kind: kindPtr, Expr: repaired},
			},
		})
	}

	dialectName := "PromQL"
	if isMetricsQL {
		dialectName = "MetricsQL"
	}
	patch := ir.DashboardPatch{
		SchemaVersion: ir.SchemaVersion,
		BaseRevision:  req.CurrentIR.Revision,
		Summary:       fmt.Sprintf("Repaired %s syntax error while retaining scope filters", dialectName),
		Operations:    ops,
	}
	raw, err := json.Marshal(patch)
	return raw, CompletionMeta{FinishReason: "stop", Model: "mock-deterministic-v1", ProviderMode: "mock"}, err
}

func buildScopeMatcher(scope *ir.ScopeFilter) string {
	if scope == nil || !validMockLabelName.MatchString(scope.LabelName) || strings.TrimSpace(scope.LabelValue) == "" {
		return ""
	}
	return fmt.Sprintf(`{%s=%q}`, scope.LabelName, scope.LabelValue)
}

func buildScopeMatcherWithExtra(scope *ir.ScopeFilter, extra string) string {
	if scope == nil || !validMockLabelName.MatchString(scope.LabelName) || strings.TrimSpace(scope.LabelValue) == "" {
		return fmt.Sprintf("{%s}", extra)
	}
	return fmt.Sprintf(`{%s=%q,%s}`, scope.LabelName, scope.LabelValue, extra)
}

func findMetric(catalog []ir.MetricCatalogItem, candidates ...string) (bool, ir.MetricCatalogItem) {
	for _, name := range candidates {
		for _, item := range catalog {
			if item.Name == name {
				return true, item
			}
		}
	}
	return false, ir.MetricCatalogItem{}
}

func findAnyOverlappingMetric(catalog []ir.MetricCatalogItem, lowerIntent string) (ir.MetricCatalogItem, bool) {
	for _, item := range catalog {
		parts := strings.Split(strings.ToLower(item.Name), "_")
		for _, p := range parts {
			if len(p) >= 3 && strings.Contains(lowerIntent, p) {
				return item, true
			}
		}
	}
	return ir.MetricCatalogItem{}, false
}

func containsAny(s string, subs ...string) bool {
	for _, sub := range subs {
		if strings.Contains(s, sub) {
			return true
		}
	}
	return false
}

func inferUnit(item ir.MetricCatalogItem) string {
	if strings.Contains(item.Name, "_seconds") {
		return "s"
	}
	if strings.Contains(item.Name, "_bytes") {
		return "bytes"
	}
	if strings.HasSuffix(item.Name, "_total") {
		return "ops"
	}
	return "short"
}

func titleFromScope(scope *ir.ScopeFilter, suffix string) string {
	if scope != nil && strings.TrimSpace(scope.LabelValue) != "" {
		return fmt.Sprintf("%s %s", scope.LabelValue, suffix)
	}
	return suffix
}

func assignCompactGrid(panels []ir.PanelIR) {
	row := 0
	col := 0
	for i := range panels {
		if len(panels) == 1 || (i == len(panels)-1 && col == 0) {
			panels[i].Layout = ir.LayoutHint{Row: row, Col: 0, Width: "full"}
			row++
			col = 0
			continue
		}
		panels[i].Layout = ir.LayoutHint{Row: row, Col: col, Width: "half"}
		if col == 0 {
			col = 1
		} else {
			col = 0
			row++
		}
	}
}

func (m *MockClient) AnalyzeStatus(ctx context.Context, req AnalyzeStatusRequest) ([]byte, CompletionMeta, error) {
	if err := m.waitDelay(ctx); err != nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, err
	}
	p := req.Payload
	isJA := p.Language == "ja"

	overallStatus := "healthy"
	confidence := "high"
	timeline := make([]ir.ReportTimelineItem, 0, 4)
	findings := make([]ir.ReportFinding, 0, 4)
	hypotheses := make([]ir.ReportHypothesis, 0, 2)
	actions := make([]ir.ReportAction, 0, 3)
	dataGaps := make([]string, 0, 4)

	if isJA {
		dataGaps = append(dataGaps, "ログおよび分散トレースは本レポートの収集対象外です。")
	} else {
		dataGaps = append(dataGaps, "Logs and distributed traces are not included in this report.")
	}

	nextFindingNum := 1
	addFinding := func(category, severity, title, detail string, evIDs []string) string {
		id := fmt.Sprintf("f-%d", nextFindingNum)
		nextFindingNum++
		findings = append(findings, ir.ReportFinding{
			ID:          id,
			Category:    category,
			Severity:    severity,
			Title:       title,
			Detail:      detail,
			EvidenceIDs: evIDs,
		})
		return id
	}

	var firstAlertID, firstMetricID string

	clampRunes := func(s string, maxRunes int) string {
		r := []rune(strings.TrimSpace(s))
		if len(r) <= maxRunes {
			return string(r)
		}
		return strings.TrimSpace(string(r[:maxRunes]))
	}

	for _, a := range p.Evidence.Alerts {
		if a.State != "active" {
			continue
		}
		if firstAlertID == "" {
			firstAlertID = a.ID
		}
		sev := "warning"
		if strings.EqualFold(a.Severity, "critical") || strings.EqualFold(a.Severity, "page") || strings.EqualFold(a.Severity, "error") {
			sev = "critical"
			overallStatus = "critical"
		} else if overallStatus == "healthy" {
			overallStatus = "degraded"
		}
		if len(timeline) < ir.MaxReportTimelineItems {
			ts := a.StartsAt
			if ts == "" {
				ts = p.Evidence.CollectedAt
			}
			evt := fmt.Sprintf("Alert %s active (%s).", a.AlertName, sev)
			if isJA {
				evt = fmt.Sprintf("アラート %s が発火中 (%s)。", a.AlertName, sev)
			}
			timeline = append(timeline, ir.ReportTimelineItem{
				Timestamp:   ts,
				Event:       clampRunes(evt, ir.MaxReportEventRunes),
				EvidenceIDs: []string{a.ID},
			})
		}
		if len(findings) < 3 {
			title := fmt.Sprintf("Active alert: %s", a.AlertName)
			detail := fmt.Sprintf("Alert %s is active (severity=%s).", a.AlertName, sev)
			if isJA {
				title = fmt.Sprintf("発火中アラート: %s", a.AlertName)
				detail = fmt.Sprintf("アラート %s が発火中です (深刻度=%s)。", a.AlertName, sev)
			}
			fid := addFinding("alert", sev, clampRunes(title, ir.MaxReportFindingTitleRunes), clampRunes(detail, ir.MaxReportFindingDetailRunes), []string{a.ID})
			if len(actions) < 2 {
				act := fmt.Sprintf("Investigate active alert %s and confirm customer impact.", a.AlertName)
				if isJA {
					act = fmt.Sprintf("発火中アラート %s の影響範囲と原因を確認してください。", a.AlertName)
				}
				prio := "short_term"
				if sev == "critical" {
					prio = "immediate"
				}
				actions = append(actions, ir.ReportAction{
					Priority:          prio,
					Action:            clampRunes(act, ir.MaxReportActionRunes),
					RelatedFindingIds: []string{fid},
				})
			}
		}
	}

	for _, r := range p.Evidence.Rules {
		if r.Health == "error" || r.Health == "nodata" {
			if overallStatus == "healthy" {
				overallStatus = "degraded"
			}
			confidence = "medium"
			if len(findings) < 5 {
				title := fmt.Sprintf("Alert rule %s health is %s", r.RuleName, r.Health)
				detail := fmt.Sprintf("Rule %s reported health=%s (state=%s).", r.RuleName, r.Health, r.State)
				if isJA {
					title = fmt.Sprintf("アラートルール %s の状態異常 (%s)", r.RuleName, r.Health)
					detail = fmt.Sprintf("ルール %s が health=%s (state=%s) を返しています。", r.RuleName, r.Health, r.State)
				}
				addFinding("monitoring_gap", "warning", clampRunes(title, ir.MaxReportFindingTitleRunes), clampRunes(detail, ir.MaxReportFindingDetailRunes), []string{r.ID})
			}
		}
	}

	for _, metric := range p.Evidence.Metrics {
		if metric.AnomalyHint == "degraded" || metric.AnomalyHint == "elevated" || metric.ThresholdBreached != "none" || metric.QueryStatus == "error" || metric.QueryStatus == "timeout" {
			if firstMetricID == "" {
				firstMetricID = metric.ID
			}
			sev := "warning"
			if metric.ThresholdBreached == "critical" || metric.AnomalyHint == "degraded" {
				sev = "critical"
				if overallStatus != "critical" {
					overallStatus = "degraded"
				}
			} else if overallStatus == "healthy" {
				overallStatus = "degraded"
			}
			if len(timeline) < ir.MaxReportTimelineItems && metric.Current != nil && metric.Current.PeakAt != "" {
				evt := fmt.Sprintf("Metric %s peaked at %.2f.", metric.PanelTitle, metric.Current.Max)
				if isJA {
					evt = fmt.Sprintf("メトリクス %s が最大値 %.2f を記録しました。", metric.PanelTitle, metric.Current.Max)
				}
				timeline = append(timeline, ir.ReportTimelineItem{
					Timestamp:   metric.Current.PeakAt,
					Event:       clampRunes(evt, ir.MaxReportEventRunes),
					EvidenceIDs: []string{metric.ID},
				})
			}
			if len(findings) < ir.MaxReportFindings {
				title := fmt.Sprintf("Performance anomaly: %s", metric.PanelTitle)
				detail := fmt.Sprintf("Panel %s status=%s trend=%s threshold=%s.", metric.PanelTitle, metric.QueryStatus, metric.Trend, metric.ThresholdBreached)
				if isJA {
					title = fmt.Sprintf("パフォーマンス異常: %s", metric.PanelTitle)
					detail = fmt.Sprintf("パネル %s (status=%s, trend=%s, threshold=%s) で異常が検知されました。", metric.PanelTitle, metric.QueryStatus, metric.Trend, metric.ThresholdBreached)
				}
				fid := addFinding("performance", sev, clampRunes(title, ir.MaxReportFindingTitleRunes), clampRunes(detail, ir.MaxReportFindingDetailRunes), []string{metric.ID})
				if len(actions) < ir.MaxReportActions {
					act := fmt.Sprintf("Inspect %s trend and compare against recent changes.", metric.PanelTitle)
					if isJA {
						act = fmt.Sprintf("%s の推移と直近の変更・デプロイとの相関を確認してください。", metric.PanelTitle)
					}
					actions = append(actions, ir.ReportAction{
						Priority:          "short_term",
						Action:            clampRunes(act, ir.MaxReportActionRunes),
						RelatedFindingIds: []string{fid},
					})
				}
			}
		}
	}

	for _, w := range p.CollectionWarnings {
		if len(dataGaps) < ir.MaxReportDataGaps {
			if msg := clampRunes(w.Message, ir.MaxReportDataGapRunes); msg != "" {
				dataGaps = append(dataGaps, msg)
			}
		}
		if w.Code == "alerting_forbidden" || w.Code == "alerting_unavailable" {
			confidence = "medium"
			if len(findings) < ir.MaxReportFindings {
				title := "Alerting telemetry partially unavailable"
				detail := clampRunes(w.Message, ir.MaxReportFindingDetailRunes)
				if isJA {
					title = "アラート情報の一部が未取得"
				}
				addFinding("monitoring_gap", "info", title, detail, []string{w.ID})
			}
		}
	}

	if firstAlertID != "" && firstMetricID != "" {
		if isJA {
			hypotheses = append(hypotheses, ir.ReportHypothesis{
				Title:             "サービス負荷増または依存先遅延によるエラー・レイテンシ悪化",
				Likelihood:        "medium",
				Rationale:         "発火中アラートと同一ウィンドウ内でダッシュボード指標の悪化が確認されています。",
				EvidenceIDs:       []string{firstAlertID, firstMetricID},
				VerificationSteps: []string{"直近のリリース差分と下流依存先のレイテンシを確認する"},
			})
		} else {
			hypotheses = append(hypotheses, ir.ReportHypothesis{
				Title:             "Service saturation or downstream latency degradation",
				Likelihood:        "medium",
				Rationale:         "Active alerting correlates with elevated dashboard performance metrics in the same window.",
				EvidenceIDs:       []string{firstAlertID, firstMetricID},
				VerificationSteps: []string{"Check recent deployment changes and downstream dependency latency."},
			})
		}
	} else if firstAlertID != "" {
		if isJA {
			hypotheses = append(hypotheses, ir.ReportHypothesis{
				Title:             "対象サービスにおける障害または閾値逸脱",
				Likelihood:        "medium",
				Rationale:         "アクティブなアラートが継続して発火しています。",
				EvidenceIDs:       []string{firstAlertID},
				VerificationSteps: []string{"対象サービスのダッシュボードとエラーログを確認する"},
			})
		} else {
			hypotheses = append(hypotheses, ir.ReportHypothesis{
				Title:             "Ongoing service fault or threshold breach",
				Likelihood:        "medium",
				Rationale:         "One or more active Grafana alerts are currently firing.",
				EvidenceIDs:       []string{firstAlertID},
				VerificationSteps: []string{"Inspect service RED metrics and recent deployment history."},
			})
		}
	}

	var summary string
	if overallStatus == "healthy" {
		if isJA {
			summary = fmt.Sprintf("直近 %s の分析では発火中アラートや重大なパフォーマンス異常は検出されませんでした。", p.Window)
		} else {
			summary = fmt.Sprintf("No active alerts or significant performance anomalies were detected over the last %s.", p.Window)
		}
	} else {
		if isJA {
			summary = fmt.Sprintf("直近 %s の分析で状態は %s と判定されました（検出事項 %d 件）。", p.Window, overallStatus, len(findings))
		} else {
			summary = fmt.Sprintf("Operational status over the last %s is %s with %d grounded finding(s).", p.Window, overallStatus, len(findings))
		}
	}

	intent := ""
	if overallStatus != "healthy" {
		scopeSuffix := ""
		if p.Scope != nil && p.Scope.LabelValue != "" {
			scopeSuffix = " for " + p.Scope.LabelValue
		}
		if isJA {
			intent = fmt.Sprintf("エラー率、p95 レイテンシ、リクエスト数の調査ダッシュボードを作成%s", scopeSuffix)
		} else {
			intent = fmt.Sprintf("Show error rate, p95 latency, and request rate investigation panels%s", scopeSuffix)
		}
	}

	report := ir.StatusReportIR{
		SchemaVersion:                ir.StatusReportSchemaVersion,
		OverallStatus:                overallStatus,
		Confidence:                   confidence,
		ExecutiveSummary:             summary,
		Timeline:                     timeline,
		Findings:                     findings,
		Hypotheses:                   hypotheses,
		RecommendedActions:           actions,
		DataGaps:                     dataGaps,
		SuggestedInvestigationIntent: intent,
	}

	raw, err := json.Marshal(report)
	if err != nil {
		return nil, CompletionMeta{ProviderMode: "mock"}, err
	}
	return raw, CompletionMeta{
		FinishReason:     "stop",
		PromptTokens:     240,
		CompletionTokens: 160,
		Model:            "mock-deterministic-report-v1",
		ProviderMode:     "mock",
	}, nil
}
